fn global_integer(name: &str, value: impl std::fmt::Display) -> String {
    format!(r#"{{"table":"globals","name":"{name}","value":{value}}}"#)
}

fn global_string(name: &str, value: &str) -> String {
    format!(
        r#"{{"table":"globals","name":"{name}","value":{}}}"#,
        quote_json(value)
    )
}

fn quote_json(value: &str) -> String {
    let mut output = String::with_capacity(value.len() + 2);
    output.push('"');
    for character in value.chars() {
        match character {
            '"' => output.push_str("\\\""),
            '\\' => output.push_str("\\\\"),
            '\n' => output.push_str("\\n"),
            '\r' => output.push_str("\\r"),
            '\t' => output.push_str("\\t"),
            '\u{08}' => output.push_str("\\b"),
            '\u{0c}' => output.push_str("\\f"),
            character if character <= '\u{1f}' => {
                write!(&mut output, "\\u{:04x}", character as u32).expect("write to String");
            }
            character => output.push(character),
        }
    }
    output.push('"');
    output
}
